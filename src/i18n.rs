//! UI language. German is the default; English can be chosen in the settings.
//!
//! Texts are written bilingually right where they are used:
//! `tr!("Abbrechen" | "Cancel")` and `trf!("{n} Dateien" | "{n} files")`.

use std::sync::atomic::{AtomicBool, Ordering};

static EN: AtomicBool = AtomicBool::new(false);

pub fn en() -> bool {
    EN.load(Ordering::Relaxed)
}

pub fn set_english(on: bool) {
    EN.store(on, Ordering::Relaxed);
}

/// Pick a static text by language.
#[macro_export]
macro_rules! tr {
    ($de:literal | $en:literal) => {
        if $crate::i18n::en() { $en } else { $de }
    };
}

/// `format!` with a German and an English template (same arguments).
#[macro_export]
macro_rules! trf {
    ($de:literal | $en:literal $(, $($arg:tt)*)?) => {
        if $crate::i18n::en() { format!($en $(, $($arg)*)?) } else { format!($de $(, $($arg)*)?) }
    };
}

